type Row = [string, string, number, number, string, string]
function sections(grade: LectureSection['grade'], book: LectureSection['book'], rows: Row[]): LectureSection[] {
  return rows.map(([stage, title, page, endPage, type, skills], index) => ({
    id: `${book}-${index + 1}`, grade, book, stage, title, type, page, endPage,
    skillIds: skills.split('|').filter(Boolean),
  }))
}

