const item = (label, rule, examples = [], caution) => ({ label, rule, ...(examples.length ? { examples } : {}), ...(caution ? { caution } : {}) })
const section = (title, summary, items) => ({ title, summary, items })
const worked = (substance, path, labels) => ({ substance, path, labels })

const SOURCE_BASIS = '依据普通高中化学课程标准和福建现行考试范围，以苏教版教材顺序校准；考法与表述参考G盘《2024版化学步步高一轮复习·新教材苏教版》及福建高考班校对资料。'

const card = (skillId, intro, overview, sections, workedExamples, checkpoints) => {
  const localDemos = sectionDemos[skillId]
  if (!localDemos || localDemos.length !== sections.length) {
    throw new Error(`${skillId} 的小节示范数量应为 ${sections.length}，实际为 ${localDemos?.length ?? 0}`)
  }
  const allWorkedExamples = [...localDemos, ...workedExamples].filter((demo, index, source) => source.findIndex((candidate) => candidate.substance === demo.substance) === index)
  return {
    skillId,
    version: 2,
    intro,
    overview,
    visualSummary: knowledgeVisualSummaries[skillId],
    sections: sections.map((knowledgeSection, sectionIndex) => ({
      ...knowledgeSection,
      items: knowledgeSection.items.map((knowledgeItem) => {
        const demo = localDemos[sectionIndex]
        return {
          ...knowledgeItem,
          examples: [...(knowledgeItem.examples ?? []), `【示范：${demo.substance}】${demo.path}`],
          visualSteps: [knowledgeItem.label, ...demo.labels].slice(0, 5),
        }
      }),
    })),
    workedExamples: allWorkedExamples,
    checkpoints,
    scopeNote: '只保留福建高中化学范围内必须理解和能够迁移的内容；更高学段理论、竞赛机理和旧选考制度内容不进入学生卡。',
    sourceBasis: SOURCE_BASIS,
  }
}

