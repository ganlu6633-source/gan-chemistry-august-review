const appendUniqueStrings = (target = [], incoming = []) => {
  const result = [...target]
  incoming.forEach((entry) => {
    if (!result.includes(entry)) result.push(entry)
  })
  return result
}

const appendUniqueObjects = (target = [], incoming = [], key) => {
  const result = [...target]
  incoming.forEach((entry) => {
    if (!result.some((existing) => existing?.[key] === entry?.[key])) result.push(entry)
  })
  return result
}

export const getP1KnowledgeCompletenessPatch = (skillId) => {
  const patch = PATCHES[skillId]
  return patch ? deepClone(patch) : null
}

export const p1KnowledgeCompletenessPatchSummary = Object.freeze({
  targetedSkills: Object.freeze(Object.keys(PATCHES)),
  addedSections: Object.values(PATCHES).reduce((total, patch) => total + patch.sections.length, 0),
  addedKnowledgePoints: Object.values(PATCHES).reduce(
    (total, patch) => total + patch.sections.reduce((count, entry) => count + entry.items.length, 0),
    0,
  ),
})

export const applyP1KnowledgeCompleteness = (cards) => {
  if (!Array.isArray(cards)) throw new TypeError('applyP1KnowledgeCompleteness(cards) 需要卡片数组')

  const clonedCards = deepClone(cards)
  clonedCards.forEach((card) => {
    const patch = PATCHES[card?.skillId]
    if (!patch) return

    card.overview = appendUniqueStrings(card.overview, patch.overview)
    card.sections = appendUniqueObjects(card.sections, patch.sections, 'title')
    card.workedExamples = appendUniqueObjects(card.workedExamples, patch.workedExamples, 'substance')
    card.checkpoints = appendUniqueStrings(card.checkpoints, patch.checkpoints)
  })

  return clonedCards
}

export default applyP1KnowledgeCompleteness
