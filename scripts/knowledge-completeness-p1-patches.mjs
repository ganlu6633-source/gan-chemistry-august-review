const p1Item = (label, rule, demoTitle, demo, visualSteps, caution) => {
  if (!Array.isArray(visualSteps) || visualSteps.length < 2) {
    throw new Error(`${label} 的 visualSteps 至少需要 2 步`)
  }

  return {
    label,
    rule,
    examples: [`【示范：${demoTitle}】${demo}`],
    visualSteps,
    ...(caution ? { caution } : {}),
  }
}

