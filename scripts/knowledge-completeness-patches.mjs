const cloneSection = (entry) => ({
  ...entry,
  items: entry.items.map((knowledgePoint) => ({
    ...knowledgePoint,
    examples: [...knowledgePoint.examples],
    visualSteps: [...knowledgePoint.visualSteps],
  })),
})

const appendUnique = (existing, additions, keyOf) => {
  const seen = new Set(existing.map(keyOf))
  const next = [...existing]
  for (const addition of additions) {
    const key = keyOf(addition)
    if (seen.has(key)) continue
    seen.add(key)
    next.push(addition)
  }
  return next
}

export const knowledgeCompletenessPatchSummary = Object.freeze({
  targetedSkills: Object.freeze(Object.keys(PATCHES)),
  addedSections: Object.values(PATCHES).reduce((total, patch) => total + patch.sections.length, 0),
  addedKnowledgePoints: Object.values(PATCHES).reduce(
    (total, patch) => total + patch.sections.reduce((count, entry) => count + entry.items.length, 0),
    0,
  ),
  addedWorkedExamples: Object.values(PATCHES).reduce((total, patch) => total + patch.workedExamples.length, 0),
  addedCheckpoints: Object.values(PATCHES).reduce((total, patch) => total + patch.checkpoints.length, 0),
})

export function applyKnowledgeCompleteness(cards) {
  if (!Array.isArray(cards)) throw new TypeError('applyKnowledgeCompleteness(cards) 需要知识卡数组。')

  const available = new Set(cards.map((card) => card.skillId))
  const missing = Object.keys(PATCHES).filter((skillId) => !available.has(skillId))
  if (missing.length) throw new Error(`知识完整性补丁缺少目标卡：${missing.join(', ')}`)

  return cards.map((card) => {
    const patch = PATCHES[card.skillId]
    if (!patch) return card

    const addedSections = patch.sections.map(cloneSection)
    const addedWorkedExamples = patch.workedExamples.map((example) => ({ ...example, labels: [...example.labels] }))

    return {
      ...card,
      sections: appendUnique(card.sections, addedSections, (entry) => entry.title),
      workedExamples: appendUnique(card.workedExamples, addedWorkedExamples, (entry) => entry.substance),
      checkpoints: appendUnique(card.checkpoints, [...patch.checkpoints], (entry) => entry),
    }
  })
}

export default applyKnowledgeCompleteness
