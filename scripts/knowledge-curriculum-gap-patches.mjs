const appendUniqueStrings = (target = [], additions = []) => {
  const result = [...target]
  for (const addition of additions) if (!result.includes(addition)) result.push(addition)
  return result
}

const appendUniqueObjects = (target = [], additions = [], key) => {
  const result = [...target]
  for (const addition of additions) {
    if (!result.some((existing) => existing?.[key] === addition?.[key])) result.push(clone(addition))
  }
  return result
}

export const curriculumGapPatchSummary = Object.freeze({
  targetedSkills: Object.freeze(Object.keys(PATCHES)),
  addedSections: Object.values(PATCHES).reduce((sum, patch) => sum + patch.sections.length, 0),
  addedKnowledgePoints: Object.values(PATCHES).reduce(
    (sum, patch) => sum + patch.sections.reduce((sectionSum, entry) => sectionSum + entry.items.length, 0),
    0,
  ),
})

export const applyCurriculumGapPatches = (cards) => {
  if (!Array.isArray(cards)) throw new TypeError('applyCurriculumGapPatches(cards) 需要知识卡数组')
  const result = clone(cards)
  const available = new Set(result.map((card) => card.skillId))
  const missing = Object.keys(PATCHES).filter((skillId) => !available.has(skillId))
  if (missing.length) throw new Error(`课程缺口补丁缺少目标卡：${missing.join(', ')}`)

  for (const card of result) {
    const patch = PATCHES[card.skillId]
    if (!patch) continue
    card.overview = appendUniqueStrings(card.overview, patch.overview)
    card.sections = appendUniqueObjects(card.sections, patch.sections, 'title')
    card.workedExamples = appendUniqueObjects(card.workedExamples, patch.workedExamples, 'substance')
    card.checkpoints = appendUniqueStrings(card.checkpoints, patch.checkpoints)
  }
  return result
}

export default applyCurriculumGapPatches
