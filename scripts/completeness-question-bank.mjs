const makeQuestion = ({
  id,
  motherId,
  skillId,
  level,
  gradeBand,
  stem,
  options,
  correctOption,
  explanation,
  scaffold,
}) => {
  const rotation = [...id].reduce((hash, character) => ((hash * 33) ^ character.charCodeAt(0)) >>> 0, 5381) % 4
  return {
    id,
    motherId,
    skillId,
    level,
    gradeBand,
    stem,
    options: options.map((_option, index) => options[(index + rotation) % options.length]),
    correctOption: (correctOption - rotation + options.length) % options.length,
    explanation,
    scaffold,
    reviewStatus: 'approved',
    scopeStatus: 'IN',
    sourceKind: 'teacher_original',
  }
}

